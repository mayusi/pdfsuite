export const WIN_ANSI = Array.from({ length: 256 }, (_, i) => WIN_HI[i] ?? (i >= 0x20 && (i < 0x7f || i > 0x9f) ? i : 0))

// Unicode → WinAnsi byte (for writing text with the standard 14 fonts)
export const UNI_TO_WIN = new Map(WIN_ANSI.map((u, i) => [u, i]).filter(([u, i]) => u && i >= 0x20))

