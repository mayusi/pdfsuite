// accented Latin letters: base letter + accent name → precomposed code point
const ACCENTS = { grave: 0x300, acute: 0x301, circumflex: 0x302, tilde: 0x303, dieresis: 0x308, ring: 0x30a, cedilla: 0x327, caron: 0x30c }
const RE_UNI = /^uni([0-9A-Fa-f]{4,})$/
const RE_U = /^u([0-9A-Fa-f]{4,6})$/
const RE_ACC = /^([A-Za-z])(grave|acute|circumflex|tilde|dieresis|ring|cedilla|caron)$/

/** Glyph name → Unicode string ('' when unknown). */
export function glyphToUnicode(gname) {
  if (!gname) return ''
  if (AGL[gname] !== undefined) return String.fromCodePoint(AGL[gname])
  if (gname.length === 1 && /[A-Za-z]/.test(gname)) return gname
  let m = gname.match(RE_UNI)
  if (m) {
    let s = ''
    for (let i = 0; i + 4 <= m[1].length; i += 4) s += String.fromCodePoint(parseInt(m[1].slice(i, i + 4), 16))
    return s
  }
  m = gname.match(RE_U)
  if (m) return String.fromCodePoint(parseInt(m[1], 16))
  m = gname.match(RE_ACC)
  if (m) return (m[1] + String.fromCodePoint(ACCENTS[m[2]])).normalize('NFC')
  const dot = gname.indexOf('.') // "a.sc", "one.oldstyle" → base glyph
  if (dot > 0) return glyphToUnicode(gname.slice(0, dot))
  const us = gname.indexOf('_') // "f_i" ligature names
  if (us > 0) return gname.split('_').map(glyphToUnicode).join('')
  return ''
}

/**
 * Build a 256-entry code → string table for a simple font's /Encoding.
 * enc: Name | Dict (BaseEncoding + Differences) | undefined. Symbolic fonts
 * without a base encoding keep identity bytes.
 */
export function simpleEncodingTable(enc, { symbolic = false } = {}) {
  const nm = (v) => (v?.k === 'n' ? v.v : null)
  let baseName = nm(enc)
  let diffs = null
  if (enc instanceof Map) {
    baseName = nm(enc.get('BaseEncoding'))
    diffs = enc.get('Differences')
  }
  const base = baseName === 'MacRomanEncoding' ? MAC_ROMAN
    : baseName === 'WinAnsiEncoding' ? WIN_ANSI
    : baseName === 'StandardEncoding' ? STANDARD
    : symbolic ? null : WIN_ANSI // spec says Standard, but WinAnsi ⊇ ASCII and matches real files better
  const table = Array.from({ length: 256 }, (_, i) => (base ? (base[i] ? String.fromCodePoint(base[i]) : '') : String.fromCharCode(i)))
  if (Array.isArray(diffs)) {
    let code = 0
    for (const d of diffs) {
      if (typeof d === 'number') code = d
      else if (d?.k === 'n') {
        if (code < 256) {
          const u = glyphToUnicode(d.v)
          if (u) table[code] = u
        }
        code++
      }
    }
  }
  return table
}

/** Unicode string → WinAnsi bytes for the standard-14 fonts (null if any char is unmappable). */
export function toWinAnsi(s) {
  const out = []
  for (const ch of s) {
    const b = UNI_TO_WIN.get(ch.codePointAt(0))
    if (b === undefined) return null
    out.push(b)
  }
  return new Uint8Array(out)
}
